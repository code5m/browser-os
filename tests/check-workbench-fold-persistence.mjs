import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve(specifier,context,next){try{return next(specifier,context)}catch(error){for(const ext of ['.ts','.mjs','.js'])try{return next(specifier+ext,context)}catch{}throw error;}}});
const data = new Map();
globalThis.localStorage = {getItem:key=>data.get(key)??null,setItem:(key,value)=>data.set(key,String(value)),removeItem:key=>data.delete(key)};
globalThis.window = {setTimeout};
const {createPinia,setActivePinia} = await import('pinia');
const {nextTick} = await import('vue');
const {hostServices} = await import('../src/capability/platform/host-services.ts');
const {useLayoutStore} = await import('../src/stores/useLayoutStore.ts');
const {useWorkbenchStore} = await import('../src/capabilities/workbench/state/useWorkbenchStore.ts');
const browser={aiNavOpen:false,setAiNavOpen(value){this.aiNavOpen=value;},activateGrid:async()=>{}};
hostServices.register('browser-context',browser);
setActivePinia(createPinia());
let layout=useLayoutStore(),workbench=useWorkbenchStore();
layout.sidebarOpen=false;layout.browserDockOpen=true;browser.aiNavOpen=true;
workbench.toggleTools();
await nextTick();
assert.equal(workbench.collapsed,true);
setActivePinia(createPinia());
browser.aiNavOpen=false;
layout=useLayoutStore();workbench=useWorkbenchStore();
assert.equal(workbench.collapsed,true,'collapsed preference survives restart');
workbench.toggleTools();
assert.equal(layout.sidebarOpen,false,'restores original closed sidebar');
assert.equal(layout.browserDockOpen,true,'restores original open dock');
assert.equal(browser.aiNavOpen,true,'restores original open AI panel');
workbench.toggleTools();
assert.equal(layout.browserDockOpen,false,'second collapse closes the restored dock');
workbench.toggleTools();
assert.equal(layout.browserDockOpen,true,'second restore keeps the latest snapshot');
data.set('workbench-layout-v1',JSON.stringify({version:1,collapsed:true}));
setActivePinia(createPinia());
layout=useLayoutStore();workbench=useWorkbenchStore();
assert.equal(workbench.collapsed,true,'legacy preferences remain readable');
workbench.toggleTools();
assert.equal(layout.sidebarOpen,true,'legacy preference uses safe default snapshot');
data.set('workbench-layout-v1',JSON.stringify({version:2,collapsed:true,snapshot:{sidebar:'false',dock:true,ai:true}}));
setActivePinia(createPinia());
layout=useLayoutStore();workbench=useWorkbenchStore();
workbench.toggleTools();
assert.equal(layout.sidebarOpen,true,'invalid snapshots do not coerce string values');
console.log('WORKBENCH_FOLD_PERSISTENCE=PASS');
