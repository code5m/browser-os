import assert from 'node:assert/strict';
import {createOperationScheduler} from '../src/shared/tasks/operationScheduler.mjs';
const s=createOperationScheduler({limits:{database:1,git:1},queueLimit:2});
const events=[];let release;
const long=s.run('database','connection-a',()=>new Promise(resolve=>{release=()=>{events.push('finish-a');resolve('ok')}}));
const same=s.run('database','connection-a',async()=>{events.push('run-same');return 2});
const git=s.run('git','repository',async()=>{events.push('run-git');return 'git'});
await new Promise(r=>setTimeout(r,0));
assert.equal(events.includes('run-git'),true,'unrelated lane must not be blocked');
assert.equal(events.includes('run-same'),false,'same resource must serialize');
assert.equal(s.inspect().find(x=>x.name==='database').pending,1);
release();
assert.equal(await long,'ok');assert.equal(await same,2);assert.equal(await git,'git');
assert.equal(s.inspect().find(x=>x.name==='database').completed,2);
const block=s.run('database','b',()=>new Promise(resolve=>{release=resolve}));
const one=s.run('database','c',async()=>1);
const two=s.run('database','d',async()=>2);
await assert.rejects(s.run('database','e',async()=>3),/BACKPRESSURE/);
release();await Promise.all([block,one,two]);
assert.ok(s.inspect().find(x=>x.name==='database').rejected>=1);
s.dispose();
await assert.rejects(s.run('git','r',async()=>1),/UNAVAILABLE/);
console.log('SHARED_OPERATION_SCHEDULER=PASS');
