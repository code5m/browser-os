import assert from 'node:assert/strict';
import {registerHooks} from 'node:module';
registerHooks({resolve(specifier,context,next){
  try{return next(specifier,context)}catch(error){
    for(const ext of ['.ts','.mjs','.js'])try{return next(specifier+ext,context)}catch{}
    throw error;
  }
}});
globalThis.window={setTimeout};
globalThis.confirm=()=>true;
const {bridge}=await import('../src/bridge.ts');
const {createPinia,setActivePinia}=await import('pinia');
const {documentOwnership}=await import('../src/application/documentOwnership.mjs');
const {useFileStore}=await import('../src/capabilities/workspace/state/useFileStore.ts');
const {useLayoutStore}=await import('../src/stores/useLayoutStore.ts');

bridge.getStartDirs=async()=>[];
bridge.editorDraftList=async()=>[];
bridge.editorDraftSave=async()=>{};
bridge.editorDraftClear=async()=>{};
bridge.listDir=async()=>[];
const disk=new Map([['/tmp/cross.txt','base']]);
let saves=0,deleted=0;
bridge.readFile=async path=>disk.get(path);
bridge.writeFileCas=async(path,baseline,content)=>{
  assert.equal(disk.get(path),baseline);
  saves++;disk.set(path,content);
};
bridge.deletePath=async()=>{deleted++};
bridge.movePath=async()=>{throw Error('NOT_EXPECTED')};
setActivePinia(createPinia());
const store=useFileStore();
await store.openFile({name:'cross.txt',path:'/tmp/cross.txt',is_dir:false,size:4});
store.setFileContent('workspace draft');
documentOwnership.replace('coding-workbench',[{path:'/tmp/cross.txt',dirty:true}]);
assert.deepEqual(documentOwnership.conflicts('workspace-overlay','/tmp/cross.txt'),['coding-workbench']);
await store.saveFile();
assert.equal(saves,0,'Coding dirty buffer blocks Workspace save');
await store.ctxDelete({name:'tmp',path:'/tmp',is_dir:true,size:0});
assert.equal(deleted,0,'dirty document in Coding blocks containing-directory delete');
documentOwnership.replace('coding-workbench',[{path:'/tmp/cross.txt',dirty:false}]);
await store.saveFile();
assert.equal(saves,1,'clean Coding buffer does not block verified native save');
const release=documentOwnership.beginSave('coding-workbench','/tmp/cross.txt');
store.setFileContent('new edits');
await store.saveFile();
assert.equal(saves,1,'in-flight Coding write blocks Workspace save');
release();
await store.saveFile();
assert.equal(saves,2);
let finishDelete;
bridge.deletePath=async()=>new Promise(resolve=>{finishDelete=resolve;});
const deleting=store.ctxDelete({name:'cross.txt',path:'/tmp/cross.txt',is_dir:false,size:4});
assert.equal(typeof finishDelete,'function');
store.setFileContent('edit while deletion is pending');
await store.saveFile();
assert.equal(saves,2,'save must not race a pending deletion');
finishDelete();
await deleting;
assert.equal(store.fileContent,'edit while deletion is pending','edits made during deletion must remain available');
assert.equal(store.editorFilePath,'/tmp/cross.txt','the retained draft must keep its original identity');
disk.set('/tmp/inline.txt','inline base');
await store.openFileInline({name:'inline.txt',path:'/tmp/inline.txt',is_dir:false,size:11});
const deletingInline=store.ctxDelete({name:'inline.txt',path:'/tmp/inline.txt',is_dir:false,size:11});
store.setInlineText('inline edit during deletion');
finishDelete();
await deletingInline;
assert.equal(store.inlineText,'inline edit during deletion','inline edits made during deletion must remain available');
assert.equal(store.inlineFile,'/tmp/inline.txt','the retained inline draft must keep its original identity');
bridge.deletePath=async()=>{throw Error('fixture delete failed');};
await store.ctxDelete({name:'other.txt',path:'/tmp/other.txt',is_dir:false,size:0});
const afterFailedDelete=documentOwnership.beginSave('other-editor','/tmp/other.txt');
afterFailedDelete();
globalThis.prompt=()=> 'renamed.txt';
let finishRename;
bridge.renamePath=async()=>new Promise(resolve=>{finishRename=resolve;});
const renaming=store.ctxRename({name:'source.txt',path:'/tmp/source.txt',is_dir:false,size:0});
assert.throws(()=>documentOwnership.beginSave('other-editor','/tmp/source.txt'),/DOCUMENT_PATH_MUTATION_IN_PROGRESS/);
assert.throws(()=>documentOwnership.beginSave('other-editor','/tmp/renamed.txt'),/DOCUMENT_PATH_MUTATION_IN_PROGRESS/);
documentOwnership.replace('coding-workbench',[{path:'/tmp/source.txt',dirty:true}]);
finishRename();await renaming;
assert.match(useLayoutStore().msg,/操作期间.*编辑/,'a new draft must be reported after rename');
documentOwnership.replace('coding-workbench',[]);
const afterRename=documentOwnership.beginSave('other-editor','/tmp/renamed.txt');afterRename();
let rejectMove;
bridge.movePath=async()=>new Promise((_resolve,reject)=>{rejectMove=reject;});
store.requestMove('/tmp/source-dir','/tmp/target');
const moving=store.confirmMove();
assert.throws(()=>documentOwnership.beginSave('other-editor','/tmp/source-dir/nested.txt'),/DOCUMENT_PATH_MUTATION_IN_PROGRESS/);
assert.throws(()=>documentOwnership.beginSave('other-editor','/tmp/target/source-dir/nested.txt'),/DOCUMENT_PATH_MUTATION_IN_PROGRESS/);
rejectMove(Error('fixture move failed'));await moving;
const afterMove=documentOwnership.beginSave('other-editor','/tmp/target/source-dir/nested.txt');afterMove();
let finishMove;
bridge.movePath=async()=>new Promise(resolve=>{finishMove=resolve;});
store.requestMove('/tmp/source-dir','/tmp/target');
const movingWithEdit=store.confirmMove();
documentOwnership.replace('coding-workbench',[{path:'/tmp/source-dir/nested.txt',dirty:true}]);
finishMove();await movingWithEdit;
assert.match(useLayoutStore().msg,/操作期间.*编辑/,'a new draft must be reported after move');
documentOwnership.replace('coding-workbench',[]);
documentOwnership.replace('workspace-overlay',[]);
console.log('CROSS_WORKBENCH_FILE_STORE=PASS');
