import assert from 'node:assert/strict';
import {createDocumentManager,normalizeDocumentPath} from '../src/shared/editor/documentManager.mjs';
const m=createDocumentManager({limit:2}),events=[];
const un=m.subscribe(s=>events.push(s));
const p=normalizeDocumentPath('/repo','main.ts');
assert.equal(p,'/repo/main.ts');
assert.throws(()=>normalizeDocumentPath('/repo','../secret'),/INVALID/);
assert.equal(m.open({path:p,content:'before',hash:'h1',owner:'coding'}).version,1);
m.open({path:p,content:'before',hash:'h1',owner:'workspace'});
assert.equal(m.edit(p,'draft',1).version,2);
assert.throws(()=>m.edit(p,'stale',1),/VERSION_CONFLICT/);
m.open({path:p,content:'disk',hash:'h2',owner:'coding'});
assert.equal(m.peek(p).content,'draft','an external read cannot overwrite another editor\'s draft');
const s=m.markSaved(p,'before','h1');assert.equal(s.dirty,true);
m.release(p,'coding');m.release(p,'workspace');
assert.equal(m.peek(p).dirty,true,'dirty draft kept when views close');
assert.ok(events.length>=3);
un();
const m2=createDocumentManager({limit:1});
m2.open({path:'/x',content:'x',owner:'a'});m2.release('/x','a');
m2.open({path:'/y',content:'y',owner:'a'});
assert.deepEqual(m2.inspect().map(x=>x.path),['/y']);
console.log('SHARED_DOCUMENT_MANAGER=PASS');
