import assert from 'node:assert/strict';
import {createAgentTaskRuntime} from '../src/shared/agent/taskRuntime.mjs';
const seen=[],contexts=[];
let release;
const runtime=createAgentTaskRuntime({maxConcurrent:1,chat:async(scope,message)=>{
  seen.push([scope,message]);
  if(message==='hold')await new Promise(resolve=>release=resolve);
  return {content:'done'};
}});
for(const id of ['browser','database','git','coding'])runtime.register({id,scope:id==='coding'?'workbench':id,readContext:async root=>{contexts.push([id,root]);return {resource:root||'selected'};}});
const a=runtime.submit({workload:'browser',instruction:'hello',withContext:false});
await new Promise(r=>setTimeout(r,0));
assert.equal(contexts.length,0,'context must not be read without consent');
assert.equal(runtime.inspect().find(t=>t.id===a).state,'succeeded');
assert.equal(seen[0][1],'hello');
const b=runtime.submit({workload:'database',instruction:'inspect',withContext:true});
await new Promise(r=>setTimeout(r,0));
assert.deepEqual(contexts,[['database','']]);
assert.ok(seen[1][1].includes('User explicitly selected untrusted context'));
const c=runtime.submit({workload:'git',instruction:'hold'});
const d=runtime.submit({workload:'coding',instruction:'after'});
assert.equal(runtime.inspect().find(t=>t.id===d).state,'queued');
assert.equal(runtime.cancel(c),true);
release();
await new Promise(r=>setTimeout(r,0));
assert.equal(runtime.inspect().find(t=>t.id===c).state,'cancelled');
assert.equal(runtime.inspect().find(t=>t.id===d).state,'succeeded');
assert.throws(()=>runtime.submit({workload:'unknown',instruction:'x'}),/NOT_READY/);
runtime.dispose();
console.log('AGENT_SHARED_TASK_RUNTIME=PASS');
