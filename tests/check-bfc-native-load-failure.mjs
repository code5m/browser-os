import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {classifyNativeTabLoadFailure, recentNativeTabLoadFailure, NATIVE_LOAD_FAILURE_TTL_MS} from '../src/capabilities/browser/model/nativeTabLoadFailure.mjs';
const tls = 'Peer failed to perform TLS handshake: The TLS connection was non-properly terminated.';
assert.equal(classifyNativeTabLoadFailure('load-failed',tls),'tls');
assert.equal(classifyNativeTabLoadFailure('load-failed','SSL connection error'),'tls');
assert.equal(classifyNativeTabLoadFailure('load-failed','HTTP 412'),'platform-limited');
assert.equal(classifyNativeTabLoadFailure('load-failed','SETTINGS_ERROR: Load failed'),'load');
assert.equal(classifyNativeTabLoadFailure('recovered',tls),null);
assert.equal(classifyNativeTabLoadFailure('unknown',tls),null);
assert.equal(recentNativeTabLoadFailure({kind:'tls',at:1000},1000+NATIVE_LOAD_FAILURE_TTL_MS),'tls');
assert.equal(recentNativeTabLoadFailure({kind:'tls',at:1000},1001+NATIVE_LOAD_FAILURE_TTL_MS),null);
assert.equal(recentNativeTabLoadFailure({kind:'tls',at:1000},999),null);
assert.equal(recentNativeTabLoadFailure(undefined,1000),null);
const browser=readFileSync(new URL('../src/capabilities/browser/state/useBrowserStore.ts',import.meta.url),'utf8');
const bfc=readFileSync(new URL('../src/capabilities/bfc/state/useBfcStore.ts',import.meta.url),'utf8');
assert.match(browser,/getRecentNativeTabFailure/);
assert.match(browser,/nativeTabFailures\.set\(event\.id/);
assert.match(browser,/nativeTabFailures\.delete\(event\.id\)/);
assert.match(bfc,/throwIfNativePageFailed\(tabId\)/);
assert.match(bfc,/BFC_NATIVE_TAB_TLS_FAILED/);
assert.match(bfc,/BFC_NATIVE_TAB_LOAD_FAILED/);
assert.doesNotMatch(browser,/document\.cookie|localStorage\.getItem\(|token\s*=/i);
console.log('BFC_NATIVE_LOAD_FAILURE=PASS (native TLS != logged_out, stale fail expires, 412 preserved, no secrets stored)');
