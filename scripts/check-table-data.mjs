#!/usr/bin/env node
import assert from 'node:assert/strict';
import {makeTableDocument,tableChanges,dirtyTable,importTableRows,exportTableSql} from '../src/capabilities/database/model/studioTable.mjs';
let count=0;
const eq=(actual,expected)=>{assert.deepEqual(actual,expected);count++;};
const rejects=fn=>{assert.throws(fn);count++;};
const columns=[{name:'id',primary:true,generated:false,binary:false},{name:'value',primary:false,generated:false,binary:false},{name:'computed',generated:true,binary:false}];
const document=makeTableDocument('item');
document.page={table:{columns},rows:[{row_id:'server-row-token',values:['9007199254740993','a','derived']}]};
eq(dirtyTable(document),false);
document.edits['server-row-token']={value:'a'};eq(tableChanges(document),[]);
document.edits['server-row-token']={value:null};eq(tableChanges(document),[{action:'update',row_id:'server-row-token',values:{value:null}}]);
eq(dirtyTable(document),true);
document.removed=['server-row-token'];eq(tableChanges(document),[{action:'delete',row_id:'server-row-token',values:{}}]);
document.removed=[];document.edits={'server-row-token':{computed:'no'}};rejects(()=>tableChanges(document));
document.edits={};document.cell={id:'server-row-token',column:'value'};eq(dirtyTable(document),true);document.cell=null;
const csv=importTableRows('id,value\r\n9007199254740993,"O\'Reilly"','csv',columns);
eq(csv[0].values,{id:'9007199254740993',value:"O'Reilly"});
eq(importTableRows('{"columns":["id","value"],"rows":[["9007199254740993",null]]}','json',columns)[0].values,{id:'9007199254740993',value:null});
rejects(()=>importTableRows('{"columns":["id"],"rows":[[9007199254740993]]}','json',columns));
rejects(()=>importTableRows('computed\na','csv',columns));
rejects(()=>importTableRows('unknown\na','csv',columns));
rejects(()=>importTableRows('value\n'+Array(101).fill('x').join('\n'),'csv',columns));
eq(importTableRows('value\n""','csv',columns)[0].values,{value:''});
eq(exportTableSql('item',['value'],[["O'Reilly"]],'sqlite'),"-- Export of the loaded rows only. Review before executing.\nINSERT INTO \"item\" (\"value\") VALUES ('O''Reilly');");
const mysql=exportTableSql('item',['value'],[["a\\' OR 1=1"]],'mysql');assert(mysql.includes('CONVERT(0x'));assert(!mysql.includes('OR 1=1'));count+=2;
eq(exportTableSql('item',['value'],[[null]],'postgres'),"-- Export of the loaded rows only. Review before executing.\nINSERT INTO \"item\" (\"value\") VALUES (NULL);");
const before=JSON.stringify(document);const another=makeTableDocument('other');another.inserts.push({id:'new',values:{value:'different'}});eq(JSON.stringify(document),before);
console.log(`TABLE_DATA_MODEL_TESTS=PASS assertions=${count}; native concurrency and rollback tests run with cargo test studio_table`);
