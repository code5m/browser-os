#!/usr/bin/env node
// Native command Owner + side-effect declarations and legacy permission debt.
// A registered permission is NOT proof of runtime authorization.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import assert from 'node:assert/strict'
const ROOT=join(dirname(fileURLToPath(import.meta.url)),'..')
const registryFile=join(ROOT,'docs/architecture/native-boundary/native-commands.yaml')
const debtFile=join(ROOT,'docs/architecture/native-boundary/native-permission-debt-baseline.json')
const reportFile=join(ROOT,'docs/architecture/native-boundary/NATIVE_OWNER_EFFECT_AUDIT_20261102.md')
const mainCapFile=join(ROOT,'src-tauri/capabilities/default.json')
const remoteCapFile=join(ROOT,'src-tauri/capabilities/browser-remote.json')
const mainAllowFile=join(ROOT,'src-tauri/permissions/default-commands.toml')
const remoteAllowFile=join(ROOT,'src-tauri/permissions/remote-collect.toml')
function entries(yaml){
  const commands=[];let c=null
  for(const line of yaml.split(/\r?\n/)){
    const name=/^  ([a-z_0-9]+):\s*$/.exec(line)
    if(name){c={name:name[1]};commands.push(c);continue}
    const field=/^    ([a-z_]+):\s*"(.*)"\s*$/.exec(line)
    if(c&&field)c[field[1]]=field[2]
  }
  return commands
}
function validate(commands,debt){
  const errors=[];const debtSet=new Set(debt)
  if(commands.length!==183)errors.push(`expected 183 existing native commands, found ${commands.length}; review inventory first`)
  if(new Set(commands.map(c=>c.name)).size!==commands.length)errors.push('duplicate names')
  for(const c of commands){
    for(const f of ['owner','file','category','resource','side_effect','permission'])if(!c[f])errors.push(`${c.name}: missing ${f}`)
    if(c.permission==='-')errors.push(`${c.name}: MISSING caller-scope permission declaration`)
  }
  return errors
}
function checkHistoricalCallerScope(entry, localAllow, remoteAllow) {
  const errors=[]
  if(!entry) return ['missing command declaration']
  if(!entry.permission.includes('tauri.default-commands(main')) errors.push('main-window caller ACL not declared')
  if(!localAllow.has(entry.name)) errors.push('not present in main-window Tauri ACL')
  const remote=remoteAllow.has(entry.name)
  if(remote && !['report_resources','report_title'].includes(entry.name)) errors.push('legacy command unexpectedly remote-callable')
  if(remote && !entry.permission.includes('tauri.remote-collect(')) errors.push('remote ACL not declared')
  if(!remote && entry.permission.includes('tauri.remote-collect(')) errors.push('false remote ACL declaration')
  return errors
}

function markdown(commands,debt){
  const owners=new Set(commands.map(c=>c.owner));const debtSet=new Set(debt)
  const open=commands.filter(c=>c.permission==='-').length
  const escape=s=>String(s??'').replaceAll('|','\\|').replaceAll('`','\\`')
  return `# Native Owner / Effect / Permission Evidence — 2026-11-02\n\n`+
    `Source: \`docs/architecture/native-boundary/native-commands.yaml\`, generated by \`node scripts/check-native-owner-effect-audit.mjs --generate\`. This is a **declaration audit**, not runtime proof.\n\n`+
    `**Registered commands:** ${commands.length}; **Owner values:** ${owners.size}; **permission '-' (undeclared):** ${open}; **side-effect reviews pending:** ${debtSet.size}.\n\n`+
    `**Hard rule:** a newly introduced \`permission: "-"\` command is rejected by the normal CI gate. All 58 legacy command caller scopes have been reconciled with real Tauri capabilities; **side-effect approvals remain unverified** until actual user-confirmation and runtime negative tests are inspected per command.\n\n`+
    `| Native command | Owner | Physical file | Declared effect | Declared permission | Evidence status |\n|---|---|---|---|---|---|\n`+
    commands.sort((a,b)=>a.name.localeCompare(b.name)).map(c=>`| \`${c.name}\` | ${escape(c.owner)} | \`${escape(c.file)}\` | ${escape(c.side_effect)} | ${escape(c.permission)} | ${debtSet.has(c.name)?'CALLER ACL VERIFIED; EFFECT REVIEW PENDING':'DECLARED, EXECUTION NOT AUDITED'} |`).join('\n')+'\n\n'+
    `**Limitations:** command presence and declared permission are not runtime privilege proof; no assertion is made about native process/PTY/DB leaks, user confirmation, external API calls, or actual installed-GUI checks. Exactly one production source-authorization and effect review is needed per command before removing debt.\n`
}
const args=process.argv.slice(2)
if(args.includes('--self-test')){
  const fixtures=entries('version: 1\ncommands:\n  foo:\n    owner: "agent"\n    file: "x.rs"\n    category: "CAPABILITY_NATIVE_ADAPTER"\n    resource: "NONE"\n    side_effect: "read"\n    permission: "-"\n')
  assert.equal(fixtures.length,1)
  assert.ok(validate(fixtures,[]).some(x=>x.includes('MISSING caller-scope permission declaration')))
  assert.ok(validate(fixtures,['foo']).some(x=>x.includes('MISSING caller-scope permission declaration')))
  assert.deepEqual(checkHistoricalCallerScope({name:'clipboard_write',permission:'tauri.default-commands(main-only)'},new Set(['clipboard_write']),new Set()),[])
  assert.ok(checkHistoricalCallerScope({name:'clipboard_write',permission:'tauri.default-commands(main-only)'},new Set(['clipboard_write']),new Set(['clipboard_write'])).some(s=>s.includes('remote-callable')))
  assert.ok(checkHistoricalCallerScope({name:'report_title',permission:'tauri.default-commands(main-only)'},new Set(['report_title']),new Set(['report_title'])).some(s=>s.includes('remote ACL not declared')))
  assert.deepEqual(checkHistoricalCallerScope({name:'report_title',permission:'tauri.default-commands(main); tauri.remote-collect(telemetry-only)'},new Set(['report_title']),new Set(['report_title'])),[])
  console.log('NATIVE_OWNER_EFFECT_AUDIT_SELF_TEST=PASS')
}else{
  const commands=entries(readFileSync(registryFile,'utf8'))
  const debt=JSON.parse(readFileSync(debtFile,'utf8')).pending_side_effect_reviews
  const errors=validate(commands,debt)
  // Verify actual installed Tauri capability scope, not registry paperwork alone.
  const local=JSON.parse(readFileSync(mainCapFile,'utf8'))
  const remote=JSON.parse(readFileSync(remoteCapFile,'utf8'))
  const localAllow=new Set([...readFileSync(mainAllowFile,'utf8').matchAll(/"([a-z][a-z0-9_]+)"/g)].map(match=>match[1]))
  const remoteAllow=new Set([...readFileSync(remoteAllowFile,'utf8').matchAll(/"([a-z][a-z0-9_]+)"/g)].map(match=>match[1]))
  if(!local.windows?.includes('main') || local.remote || !local.permissions?.includes('default-commands') || local.webviews) errors.push('Native main capability is not local main-only')
  if(!remote.remote || !remote.permissions?.includes('remote-collect') || remote.permissions?.includes('default-commands')) errors.push('Remote webview must not have main native command set')
  for(const command of debt) {
    const entry=commands.find(c=>c.name===command)
    const issues=checkHistoricalCallerScope(entry,localAllow,remoteAllow)
    for(const issue of issues) errors.push(`${command}: ${issue}`)
  }
  if(errors.length){console.error(errors.join('\n'));process.exit(1)}
  const body=markdown(commands,debt)
  if(args.includes('--generate'))writeFileSync(reportFile,body)
  else if(args.includes('--check')){if(readFileSync(reportFile,'utf8')!==body){console.error('NATIVE_OWNER_EFFECT_AUDIT_DRIFT');process.exit(1)}}
  else throw Error('Usage --generate | --check | --self-test')
  console.log(`NATIVE_OWNER_EFFECT_AUDIT=PASS commands=${commands.length} undeclared_permissions=${commands.filter(c=>c.permission==='-').length} pending_effect_reviews=${debt.length} main_acl_verified=${debt.length}/${debt.length}`)
}
